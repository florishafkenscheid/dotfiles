local send_animation_generation = {}

local function send_window_to_workspace(target_workspace_id)
    local window = hl.get_active_window()
    if not window or not window.workspace or window.workspace.id == target_workspace_id then
        return
    end

    local source_monitor = window.monitor or window.workspace.monitor
    local target_workspace = hl.get_workspace(target_workspace_id)
    local target_monitor = target_workspace and target_workspace.monitor or source_monitor
    local direction

    -- Physical monitor placement takes precedence. Within one monitor, higher
    -- workspace numbers are to the right and lower numbers are to the left.
    if source_monitor and target_monitor and source_monitor.x ~= target_monitor.x then
        direction = target_monitor.x > source_monitor.x and "right" or "left"
    else
        direction = target_workspace_id > window.workspace.id and "right" or "left"
    end

    local window_id = window.stable_id
    send_animation_generation[window_id] = (send_animation_generation[window_id] or 0) + 1
    local generation = send_animation_generation[window_id]

    hl.dispatch(hl.dsp.window.set_prop({
        prop = "animation",
        value = "slide " .. direction,
        window = window,
    }))
    hl.dispatch(hl.dsp.window.move({
        workspace = target_workspace_id,
        follow = false,
        window = window,
    }))

    -- Keep the directional override only for this transfer. The generation
    -- guard prevents an older timer from clearing a newer rapid transfer.
    hl.timer(function()
        if send_animation_generation[window_id] == generation then
            hl.dispatch(hl.dsp.window.set_prop({
                prop = "animation",
                value = "unset",
                window = window,
            }))
            send_animation_generation[window_id] = nil
        end
    end, { timeout = 200, type = "oneshot" })
end

for workspace = 1, 10 do
    local key = workspace % 10
    local target_workspace_id = workspace
    hl.bind(main_mod .. " + " .. key, hl.dsp.focus({ workspace = workspace }))
    hl.bind(main_mod .. " + SHIFT + " .. key, function()
        send_window_to_workspace(target_workspace_id)
    end)
end

